import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const directory = new URL('../apps/scale-print/public/',import.meta.url);
const order = ['config.mjs','cloud-config.mjs','production.mjs','transport.mjs','connection.mjs','cloud.mjs','scale.mjs','app.mjs'];
export async function renderScaleBundle() {
  const parts=[];
  for(const name of order) {
    const source=await readFile(new URL(name,directory),'utf8');
    const body=source.replace(/^import[^\n]+;\r?\n/gm,'').replace(/^export (?=(?:const|function|class|async function)\b)/gm,'');
    if(/^\s*(?:import|export)\s/m.test(body))throw new Error(`Unsupported module syntax in ${name}`);
    parts.push(`// ${name}\n${body.trim()}`);
  }
  return `// Generated by scripts/bundle-scale.mjs.\n(function () {\n'use strict';\n\n${parts.join('\n\n')}\n})();\n`;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const content=await renderScaleBundle(),target=new URL('app.bundle.js',directory);
  if(process.argv.includes('--check')) {if(content!==await readFile(target,'utf8'))throw new Error('Scale bundle is stale.');}
  else {await writeFile(target,content,'utf8');console.log('Built isolated scale test bundle');}
}
