import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const directory = new URL('../apps/label-print/public/', import.meta.url);
const order = ['config.mjs','cloud-config.mjs','production.mjs','transport.mjs','connection.mjs','cloud.mjs','app.mjs'];

// These buildless modules use named declarations and single-line relative imports only.
// Keep the authored modules for tests; emit one classic script for file:// previews.
export async function renderBundle() {
  const parts = [];
  for (const name of order) {
    const source = await readFile(new URL(name,directory),'utf8');
    const body = source.replace(/^import[^\n]+;\r?\n/gm,'').replace(/^export (?=(?:const|function|class|async function)\b)/gm,'');
    if (/^\s*(?:import|export)\s/m.test(body)) throw new Error(`Unsupported module syntax in ${name}`);
    parts.push(`// ${name}\n${body.trim()}`);
  }
  return `// Generated by scripts/bundle.mjs. Edit the .mjs source files, then run npm run build.\n(function () {\n'use strict';\n\n${parts.join('\n\n')}\n})();\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = await renderBundle();
  const destination = new URL('app.bundle.js',directory);
  if (process.argv.includes('--check')) {
    if (source !== await readFile(destination,'utf8')) throw new Error('app.bundle.js is stale. Run npm run build.');
  } else {
    await writeFile(destination,source,'utf8');
    console.log('Built app.bundle.js (local-file and HTTP preview)');
  }
}
